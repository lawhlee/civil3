export function barExamAttribution(item) {
  const source = BAR_EXAM_SOURCES[`${item.set || '2026-09'}:${item.number || item.q || item.n}`];
  if (!source) return null;
  const reference = `제${source.round}회(${source.year}년) 변호사시험 민사법 선택형 ${source.number}번`;
  const identical = source.matchType === 'identical';
  const basis = identical
    ? '바탕 연습문제는 기출 원문과 동일합니다.'
    : `바탕 연습문제는 해당 기출의 변형입니다. ${source.note}.`;
  if (item.type === 'ox') {
    return {reference, label: '변형 · O/X 재구성', note: `${basis} 현재 문제는 그 연습문제에서 지문을 골라 O/X로 구성했습니다.${item.origin === 'variant' ? ' 지문의 내용도 변경했습니다.' : ''}`};
  }
  if (item.origin === 'variant') {
    return {reference, label: '변형 · 사례 재구성', note: `${basis} 현재 문제는 지문과 답 조합을 추가로 변경한 사례변형입니다.`};
  }
  if (item.optionsReordered) {
    return {reference, label: '변형 · 선택지 순서 변경', note: `${basis} 현재 문제는 선택지 순서를 변경했습니다.`};
  }
  return {reference, label: identical ? '기출 동일' : '기출 변형', note: identical ? '문제와 선택지 내용·순서가 기출 원문과 동일합니다.' : source.note};
}
